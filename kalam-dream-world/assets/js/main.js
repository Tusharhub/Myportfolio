    function starfield(canvas) {
      if (!canvas.getContext) return;
      var ctx = canvas.getContext('2d');
      var dpr = Math.min(window.devicePixelRatio || 1, 2);
      var stars = [], w = 0, h = 0, raf = null, running = true;

      function build() {
        var rect = canvas.parentNode.getBoundingClientRect();
        if (stars.length && Math.abs(rect.width - w) < 2 && Math.abs(rect.height - h) < 60) return;
        w = rect.width;
        h = rect.height;
        canvas.width = Math.round(w * dpr);
        canvas.height = Math.round(h * dpr);
        ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

        var count = Math.round(Math.min(170, (w * h) / 6500));
        stars = [];
        for (var i = 0; i < count; i++) {
          stars.push({
            x: Math.random() * w,
            y: Math.random() * h,
            r: Math.random() * 1.15 + 0.25,
            a: Math.random() * 0.55 + 0.25,
            s: Math.random() * 0.0012 + 0.0002,
            p: Math.random() * Math.PI * 2,
            warm: Math.random() < 0.06
          });
        }
        draw(0);
      }

      function draw(t) {
        ctx.clearRect(0, 0, w, h);
        for (var i = 0; i < stars.length; i++) {
          var s = stars[i];
          ctx.globalAlpha = reduceMotion ? s.a : s.a * (0.6 + 0.4 * Math.sin(t * s.s + s.p));
          ctx.fillStyle = s.warm ? '#F2A93B' : '#FFFFFF';
          ctx.beginPath();
          ctx.arc(s.x, s.y, s.r, 0, Math.PI * 2);
          ctx.fill();
        }
        ctx.globalAlpha = 1;
      }

      function loop(t) {
        if (!running) return;
        draw(t);
        raf = window.requestAnimationFrame(loop);
      }

      build();
      $win.on('resize', debounce(build, 200));
      if (reduceMotion) return;

      if (hasIO) {
        // Only animate while the hero is on screen
        new IntersectionObserver(function (entries) {
          running = entries[0].isIntersecting;
          window.cancelAnimationFrame(raf);
          if (running) raf = window.requestAnimationFrame(loop);
        }).observe(canvas);
      } else {
        raf = window.requestAnimationFrame(loop);
      }
    }

